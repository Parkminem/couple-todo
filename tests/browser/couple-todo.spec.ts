test("saves notification choices and a valid overnight quiet period", async ({ page }) => {
  await page.goto("/notifications")
  const settings = page.getByRole("button", { name: "알림 설정" })
  await settings.click()
  const dialog = page.getByRole("dialog", { name: "알림 설정" })
  await expect(dialog.getByText(/홈 화면에 추가/)).toBeVisible()
  await expect(dialog.getByRole("button", { name: "이 기기에서 켜기" })).toBeDisabled()
  const added = dialog.getByRole("switch", { name: "할 일 추가" })
  const quiet = dialog.getByRole("switch", { name: "방해 금지 시간" })
  await expect(added).toBeChecked()
  await added.uncheck()
  await quiet.check()
  await dialog.getByLabel("종료 시간").fill("22:00")
  await dialog.getByRole("button", { name: "저장하기" }).click()
  await expect(dialog.getByRole("alert")).toContainText("서로 다르게")
  await dialog.getByLabel("종료 시간").fill("07:30")
  await dialog.getByRole("button", { name: "저장하기" }).click()
  await expect(dialog).toHaveCount(0)
  await settings.click()
  await expect(added).not.toBeChecked()
  await expect(quiet).toBeChecked()
  await expect(dialog.getByLabel("종료 시간")).toHaveValue("07:30")
})
