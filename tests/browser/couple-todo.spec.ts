test("the shared assignee opens both overlapping profiles while the card opens task details", async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/")
  const details = page.getByRole("button", { name: "주말 장보기 상세" })
  const card = page.locator(".task-card").filter({ has: details })
  const together = card.getByRole("button", { name: "함께 프로필 사진 크게 보기" })
  await expect(together).toBeVisible()
  await expect(together.locator(".profile-avatar")).toHaveCount(2)

  await together.getByText("함께", { exact: true }).tap()
  const preview = page.getByRole("dialog", { name: "민혁 · 그녀", exact: true })
  await expect(preview).toBeVisible()
  const circles = preview.locator(".profile-avatar")
  await expect(circles).toHaveCount(2)
  const first = (await circles.nth(0).boundingBox())!
  const second = (await circles.nth(1).boundingBox())!
  expect(first.width).toBeGreaterThan(120)
  expect(Math.abs(first.width - second.width)).toBeLessThan(1)
  expect(second.x).toBeGreaterThan(first.x + first.width * 0.75)
  expect(second.x).toBeLessThan(first.x + first.width)
  expect(Math.abs(second.y - first.y)).toBeLessThan(1)
  await page.screenshot({ path: info.outputPath("together-preview.png"), animations: "disabled", caret: "initial", scale: "css" })
  await expect(page.getByRole("dialog", { name: "할 일 편집" })).toHaveCount(0)
  await preview.getByRole("button", { name: "닫기" }).click()
  await expect(together).toBeFocused()

  const date = (await card.locator(".task-date").boundingBox())!
  await page.mouse.click(date.x + date.width / 2, date.y + date.height / 2)
  const sheet = page.getByRole("dialog", { name: "할 일 편집" })
  await expect(sheet.getByRole("textbox", { name: "할 일 제목" })).toHaveValue("주말 장보기")
  await sheet.getByRole("button", { name: "닫기" }).click()
  await card.getByRole("checkbox", { name: "주말 장보기 완료" }).click()
  await expect(page.getByRole("region", { name: /^완료/ }).getByRole("checkbox", { name: "주말 장보기 완료" })).toBeChecked()
})

test("a saved profile photo can be enlarged, follows the assignee and can be reset", async ({ page }, info) => {
  await page.goto("/us")
  const member = page.getByRole("listitem").filter({ hasText: "민혁 (나)" })
  const photo = member.locator("img")
  const edit = page.getByRole("button", { name: "프로필 사진 편집" })
  await expect(member.locator("svg")).toBeVisible()
  await edit.click()
  const dialog = page.getByRole("dialog", { name: "프로필 사진 편집" })
  const save = dialog.getByRole("button", { name: "저장하기" })
  await expect(save).toBeDisabled()
  await dialog.getByLabel("프로필 사진 파일").setInputFiles("public/icons/icon-512.png")
  await expect(dialog.locator("img")).toHaveJSProperty("naturalWidth", 512)
  await expect(dialog.locator("img")).toHaveJSProperty("naturalHeight", 512)
  await expect(photo).toHaveCount(0)
  await save.click()
  await expect(photo).toHaveJSProperty("naturalWidth", 192)
  await expect(photo).toHaveAttribute("alt", "")

  const ownProfile = member.getByRole("button", { name: /민혁.*프로필 사진 크게 보기/ })
  await ownProfile.click()
  const ownPreview = page.getByRole("dialog", { name: "민혁" })
  const enlarged = ownPreview.locator("img")
  await expect(enlarged).toHaveJSProperty("naturalWidth", 512)
  expect((await enlarged.boundingBox())?.width).toBeGreaterThan(180)
  const close = ownPreview.getByRole("button", { name: "닫기" })
  await expect(close).toBeFocused()
  await close.press("Escape")
  await expect(ownPreview).toHaveCount(0)
  await expect(ownProfile).toBeFocused()

  await page.getByRole("link", { name: "투두", exact: true }).click()
  const avatars = page.getByRole("group", { name: "나와 그녀" })
  await expect(avatars.locator("img")).toBeVisible()
  await avatars.getByRole("button", { name: "민혁 프로필 사진 크게 보기" }).click()
  await expect(enlarged).toHaveJSProperty("naturalWidth", 512)
  await page.screenshot({ path: info.outputPath("profile-preview.png"), animations: "disabled", caret: "initial" })
  await page.mouse.click(8, 8)
  await expect(ownPreview).toHaveCount(0)

  await avatars.getByRole("button", { name: "그녀 프로필 사진 크게 보기" }).click()
  const partnerPreview = page.getByRole("dialog", { name: "그녀" })
  await expect(partnerPreview.locator(".profile-avatar svg")).toBeVisible()
  await partnerPreview.getByRole("button", { name: "닫기" }).click()
  await expect(partnerPreview).toHaveCount(0)
  for (const screen of ["투두", "캘린더"]) {
    if (screen === "캘린더") await page.getByRole("link", { name: screen, exact: true }).click()
    for (const [title, photos] of [["주말 장보기", 1], ["영화 예매하기", 1], ["카페 예약하기", 0]] as const) {
      const row = page.getByRole("button", { name: `${title} 상세` })
      await expect(row).toBeVisible()
      await expect(page.locator(".task-card").filter({ has: row }).locator("img")).toHaveCount(photos)
    }
    const mine = page.locator(".task-card").filter({ has: page.getByRole("button", { name: "영화 예매하기 상세" }) })
    await mine.getByRole("button", { name: "나 프로필 사진 크게 보기" }).click()
    await expect(enlarged).toHaveJSProperty("naturalWidth", 512)
    await ownPreview.getByRole("button", { name: "닫기" }).click()
    const shared = page.locator(".task-card").filter({ has: page.getByRole("button", { name: "주말 장보기 상세" }) })
    await shared.getByRole("button", { name: "함께 프로필 사진 크게 보기" }).click()
    const pairPreview = page.getByRole("dialog", { name: "민혁 · 그녀" })
    await expect(pairPreview.locator("img")).toHaveJSProperty("naturalWidth", 512)
    await expect(pairPreview.locator(".profile-avatar-partner svg")).toBeVisible()
    await pairPreview.getByRole("button", { name: "닫기" }).click()
  }

  await page.getByRole("link", { name: "우리", exact: true }).click()
  await page.locator(".pair-people").getByRole("button", { name: "그녀 프로필 사진 크게 보기" }).click()
  await expect(partnerPreview).toBeVisible()
  await partnerPreview.getByRole("button", { name: "닫기" }).click()
  await edit.click()
  await dialog.getByRole("button", { name: "기본 이미지 사용" }).click()
  await expect(dialog).toHaveCount(0)
  await expect(photo).toHaveCount(0)
  await expect(member.locator("svg")).toBeVisible()
})

