for (const [width, height] of [[375, 812], [390, 844], [402, 874], [430, 932]]) {
  test(`renders and captures four screens at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height })
    await page.goto("/")
    await expect(page.getByRole("heading", { name: "우리의 할 일" })).toBeVisible()
    for (const [name, slug] of [["투두", "todo"], ["캘린더", "calendar"], ["통계", "stats"], ["우리", "us"]]) {
      if (slug !== "todo") await page.getByRole("link", { name, exact: true }).click()
      await expect(page.getByRole("link", { name, exact: true })).toHaveAttribute("aria-current", "page")
      const fonts = await page.evaluate(async () => {
        await document.fonts.ready
        return Promise.all([
          document.fonts.load('700 32px "SUITE Variable"', "우리의 할 일"),
          document.fonts.load('600 16px "SUIT Variable"', "주말 장보기"),
          document.fonts.load('700 28px "Geist Sans"', "123"),
        ]).then(loaded => loaded.every(faces => faces.length > 0 && faces.every(face => face.status === "loaded")))
      })
      expect(fonts).toBe(true)
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
      const filename = info.outputPath(`${slug}-${width}.png`)
      await page.screenshot({ path: filename, animations: "disabled", scale: "css" })
      await info.attach( filename.split("/").at(-1)!, { path: filename, contentType: "image/png" })
    }
  })
}

test("safe-area padding, scroll and focus keep the last task accessible", async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 667 })
  await page.goto("/")
  await page.addStyleTag({ content: ":root { --safe-top: 59px; --safe-bottom: 34px }" })
  const home = page.getByRole("heading", { name: "우리의 할 일" })
  const nav = page.getByRole("navigation", { name: "하단 메뉴" })
  expect((await home.boundingBox())!.y).toBeGreaterThan(59)
  expect((await nav.boundingBox())!.height).toBeGreaterThan(104)
  const lastTask = page.getByRole("button", { name: "집 청소하기 상세" })
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
  expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(0)
  expect((await lastTask.boundingBox())!.y + (await lastTask.boundingBox())!.height).toBeLessThan((await nav.boundingBox())!.y)
  await lastTask.click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await page.getByRole("textbox", { name: "할 일 제목" }).focus()
  await expect(page.getByRole("textbox", { name: "할 일 제목" })).toBeFocused()
})

